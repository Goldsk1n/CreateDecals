package com.goldskinmc.createdecals.registry;

import static com.goldskinmc.createdecals.CreateDecals.REGISTRATE;

import com.goldskinmc.createdecals.CreateDecals;
import com.simibubi.create.AllBlocks;
import com.simibubi.create.AllItems;
import com.tterrag.registrate.providers.ProviderType;
import com.tterrag.registrate.providers.RegistrateRecipeProvider;
import net.minecraft.advancements.critereon.InventoryChangeTrigger;
import net.minecraft.data.recipes.RecipeCategory;
import net.minecraft.data.recipes.ShapedRecipeBuilder;
import net.minecraft.data.recipes.ShapelessRecipeBuilder;
import net.minecraft.data.recipes.SingleItemRecipeBuilder;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.tags.ItemTags;
import net.minecraft.tags.TagKey;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.crafting.Ingredient;
import net.neoforged.neoforge.common.Tags;

/**
 * Recipes from Create's own parts, no new machines (plan Decision 9). Decal Blocks come off the Stonecutter, where Create
 * makes its copycats: two from a zinc ingot. Create's own Copycat Panels and Steps take decals as they are, so they need no
 * recipe of ours. A Decal Stencil is shaped like its icon:
 * an iron sheet with a brass nugget in each corner and any dye under it (owner, Nov 9). Tags as Create's own tools use
 * them. Generated by {@code runData}.
 */
public final class DecalsRecipes {
    private DecalsRecipes() {
    }

    public static void register() {
        REGISTRATE.addDataGenerator(ProviderType.RECIPE, DecalsRecipes::recipes);
    }

    private static TagKey<Item> tag(String path) {
        return ItemTags.create(ResourceLocation.fromNamespaceAndPath("c", path));
    }

    private static void recipes(RegistrateRecipeProvider out) {
        ShapedRecipeBuilder.shaped(RecipeCategory.TOOLS, DecalsItems.DECAL_STENCIL)
                .pattern("N N")
                .pattern(" S ")
                .pattern("NDN")
                .define('N', tag("nuggets/brass"))
                .define('S', tag("plates/iron"))
                .define('D', Tags.Items.DYES)
                .unlockedBy("has_iron_sheet", InventoryChangeTrigger.TriggerInstance.hasItems(AllItems.IRON_SHEET.get()))
                .unlockedBy("has_brass_nugget", InventoryChangeTrigger.TriggerInstance.hasItems(AllItems.BRASS_NUGGET.get()))
                .save(out);
        SingleItemRecipeBuilder.stonecutting(Ingredient.of(tag("ingots/zinc")),
                        RecipeCategory.BUILDING_BLOCKS, DecalsBlocks.DECAL_BLOCK, 2)
                .unlockedBy("has_zinc_ingot", InventoryChangeTrigger.TriggerInstance.hasItems(AllItems.ZINC_INGOT.get()))
                .save(out, CreateDecals.id("decal_block"));
    }
}
